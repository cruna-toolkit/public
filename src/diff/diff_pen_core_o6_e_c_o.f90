module diff_pen_core_o6_e_c_o


  use parameter

  private
  public :: diff_i1, diff_i2, diff_i3

  character(len=max_length_parameter), parameter, public :: diff_type = 'open'
  character(len=max_length_parameter), parameter, public :: diff_name = 'diff_pen_core_o6_e_c_o'

contains

!!!=================================================================================================
  subroutine diff_i1(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout) :: q
    real(kind=rk)                , intent(in)    :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    call diff_main(q,dx)
  end subroutine diff_i1
!!!==================================================================================================

!!!=================================================================================================
  subroutine diff_i2(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout) :: q
    real(kind=rk)                , intent(in)    :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    call diff_main(q,dx)
  end subroutine diff_i2
!!!==================================================================================================

!!!=================================================================================================
  subroutine diff_i3(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout) :: q
    real(kind=rk)                , intent(in)    :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    call diff_main(q,dx)
  end subroutine diff_i3
!!!==================================================================================================


!!!=================================================================================================
  subroutine diff_main(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
!!! 6th order explicit, central stencil (open boundaries)
!!! Interior: 7-point central: (-1, 9, -45, 0, 45, -9, 1) / 60
!!! Boundaries: 7-point one-sided, 6th-order accurate (first three & last three lines)
!!! Source: Fornberg, B. 1988,Generation of finite difference formulas on arbitrarily spaced grids
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout) :: q
    real(kind=rk)                , intent(in)    :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), allocatable   :: q_tmp
    integer                                      :: n1,n2
    integer                                      :: i,j

    n1 = size(q,1)
    n2 = size(q,2)

    allocate(q_tmp(n1,n2))

    !---------------------------
    ! Left boundary (i = 1,2,3)
    !---------------------------
    ! i = 1: [-147, 360, -450, 400, -225, 72, -10] / 60
    q_tmp(1,:) = -147.0_rk*q(1,:) + 360.0_rk*q(2,:) - 450.0_rk*q(3,:) + 400.0_rk*q(4,:) &
                 -225.0_rk*q(5,:) +  72.0_rk*q(6,:)  -  10.0_rk*q(7,:)

    ! i = 2: [-10, -77, 150, -100, 50, -15, 2] / 60
    q_tmp(2,:) =  -10.0_rk*q(1,:) -  77.0_rk*q(2,:) + 150.0_rk*q(3,:) - 100.0_rk*q(4,:) &
                   +50.0_rk*q(5,:) -  15.0_rk*q(6,:) +   2.0_rk*q(7,:)

    ! i = 3: [2, -24, -35, 80, -30, 8, -1] / 60
    q_tmp(3,:) =    2.0_rk*q(1,:) -  24.0_rk*q(2,:) -  35.0_rk*q(3,:) +  80.0_rk*q(4,:) &
                   -30.0_rk*q(5,:) +   8.0_rk*q(6,:) -   1.0_rk*q(7,:)

    !---------------------------
    ! Interior (i = 4 .. n1-3)
    ! 7-point central: (-1, 9, -45, 0, 45, -9, 1) / 60
    !---------------------------
    do j = 1, n2
       do i = 4, (n1-3)
          q_tmp(i,j) = -1.0_rk*q(i-3,j) +  9.0_rk*q(i-2,j) - 45.0_rk*q(i-1,j) &
                                 + 45.0_rk*q(i+1,j) -  9.0_rk*q(i+2,j) +  1.0_rk*q(i+3,j)
       end do
    end do

    !---------------------------
    ! Right boundary (i = n1-2, n1-1, n1)
    ! Mirror of the left stencils
    !---------------------------
    ! i = n1-2: [1, -8, 30, -80, 35, 24, -2] / 60
    q_tmp(n1-2,:) =   1.0_rk*q(n1-6,:) -   8.0_rk*q(n1-5,:) +  30.0_rk*q(n1-4,:) &
                     -80.0_rk*q(n1-3,:) +  35.0_rk*q(n1-2,:) +  24.0_rk*q(n1-1,:) - 2.0_rk*q(n1,:)

    ! i = n1-1: [-2, 15, -50, 100, -150, 77, 10] / 60
    q_tmp(n1-1,:) =  -2.0_rk*q(n1-6,:) +  15.0_rk*q(n1-5,:) -  50.0_rk*q(n1-4,:) + 100.0_rk*q(n1-3,:) &
                    -150.0_rk*q(n1-2,:) +  77.0_rk*q(n1-1,:) +  10.0_rk*q(n1,:)

    ! i = n1: [10, -72, 225, -400, 450, -360, 147] / 60
    q_tmp(n1,:)   =  10.0_rk*q(n1-6,:) -  72.0_rk*q(n1-5,:) + 225.0_rk*q(n1-4,:) - 400.0_rk*q(n1-3,:) &
                     +450.0_rk*q(n1-2,:) - 360.0_rk*q(n1-1,:) + 147.0_rk*q(n1,:)

    ! Scale by dx (common denominator 60 pulled out)
    q = q_tmp / (dx * 60.0_rk)

  end subroutine diff_main
!!!=================================================================================================

end module diff_pen_core_o6_e_c_o
