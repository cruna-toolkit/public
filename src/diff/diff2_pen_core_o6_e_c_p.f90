module diff2_pen_core_o6_e_c_p

  use parameter

  private

  public :: diff2_i1, diff2_i2, diff2_i3

  character(len=max_length_parameter), parameter, public :: diff2_type = 'periodic'
  character(len=max_length_parameter), parameter, public :: diff2_name = 'diff2_pen_core_o6_e_c_p'

contains

!!!=================================================================================================
  subroutine diff2_i1(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout)      :: q
    real(kind=rk)                , intent(in)         :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

    call diff_main(q,dx)

  end subroutine diff2_i1
!!!==================================================================================================

!!!=================================================================================================
  subroutine diff2_i2(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout)       :: q
    real(kind=rk)                , intent(in)          :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

    call diff_main(q,dx)

  end subroutine diff2_i2
!!!==================================================================================================

!!!=================================================================================================
  subroutine diff2_i3(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), dimension(:,:), intent(inout)       :: q
    real(kind=rk)                , intent(in)          :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

    call diff_main(q,dx)

  end subroutine diff2_i3
!!!==================================================================================================


!!!=================================================================================================
  subroutine diff_main(q,dx)
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
!!! 4th order explicit, stencil from PIVR code
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk) , dimension(:,:), intent(inout)       :: q
    real(kind=rk)                 , intent(in)          :: dx
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk) , dimension(:,:), allocatable         :: q_tmp
    integer                                             :: n1,n2
    integer                                             :: i,j
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
    real(kind=rk), parameter :: c0 = -490.0_rk
    real(kind=rk), parameter :: c1 =  270.0_rk
    real(kind=rk), parameter :: c2 =  -27.0_rk
    real(kind=rk), parameter :: c3 =    2.0_rk    
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!    

    n1 = size(q,1)
    n2 = size(q,2)

    allocate(q_tmp(n1,n2))

  ! compute A* 
  ! left
    q_tmp(1,:) = c3*q(4,:) + c2*q(3,:) + c1*q(2,:) + c0*q(1,:) + c1*q(n1,:) + c2*q(n1-1,:) + c3*q(n1-2,:)
    q_tmp(2,:) = c3*q(5,:) + c2*q(4,:) + c1*q(3,:) + c0*q(2,:) + c1*q(1,:)  + c2*q(n1,:)   + c3*q(n1-1,:)
    q_tmp(3,:) = c3*q(6,:) + c2*q(5,:) + c1*q(4,:) + c0*q(3,:) + c1*q(2,:)  + c2*q(1,:)    + c3*q(n1,:)
    
    ! inner
    do j = 1, n2
      do i = 4, n1-3
         q_tmp(i,j) = c3*q(i+3,j) + c2*q(i+2,j) + c1*q(i+1,j) + c0*q(i,j) + c1*q(i-1,j) + c2*q(i-2,j) + c3*q(i-3,j)
      end do
    end do
    
    ! right
    q_tmp(n1-2,:) = c3*q(1,:) + c2*q(n1,:) + c1*q(n1-1,:) + c0*q(n1-2,:) + c1*q(n1-3,:) + c2*q(n1-4,:) + c3*q(n1-5,:)
    q_tmp(n1-1,:) = c3*q(2,:) + c2*q(1,:)  + c1*q(n1,:)   + c0*q(n1-1,:) + c1*q(n1-2,:) + c2*q(n1-3,:) + c3*q(n1-4,:)
    q_tmp(n1  ,:) = c3*q(3,:) + c2*q(2,:)  + c1*q(1,:)    + c0*q(n1,:)   + c1*q(n1-1,:) + c2*q(n1-2,:) + c3*q(n1-3,:)
    
    ! scale with dx^2
    q = q_tmp / (dx**2.0_rk * 180.0_rk)

  end subroutine diff_main
!!!==================================================================================================

end module diff2_pen_core_o6_e_c_p